import { spawnSync } from "node:child_process";
import { existsSync } from "node:fs";
import { mkdir, stat, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { syncApplicationIdentity } from "./application-identity.mjs";

const website = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const repo = resolve(website, "..");
const python = resolve(repo, "scripts/agent-python");
await syncApplicationIdentity();

async function ensureSkillsIndex() {
  const path = resolve(website, "docs/api/skills-index.json");
  try {
    if (Date.now() - (await stat(path)).mtimeMs < 24 * 60 * 60 * 1000) return;
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
  }
  try {
    const response = await fetch("https://hermes-agent.nousresearch.com/docs/api/skills-index.json", {
      signal: AbortSignal.timeout(30_000),
    });
    if (!response.ok) throw new Error(`HTTP ${response.status}`);
    const content = await response.text();
    if (!Array.isArray(JSON.parse(content).skills)) throw new Error("No skills array in the external catalog");
    await mkdir(resolve(website, "docs/api"), { recursive: true });
    await writeFile(path, content);
  } catch (error) {
    console.warn(`External skill index unavailable; retaining the local catalog: ${error.message}`);
  }
}

function run(command, args) {
  const result = spawnSync(command, args, { cwd: repo, stdio: "inherit" });
  if (result.error) throw result.error;
  if (result.status !== 0) process.exit(result.status ?? 1);
}

// Author-written documentation is never regenerated by a preview/build.
// Explicit `just docs-generate` remains the operation that refreshes skill pages.
const outputs = [
  ["extract-skills.py", "api/skills.json"],
  ["extract-automation-blueprints.py", "api/automation-blueprints-index.json"],
  ["extract-plugins.py", "api/plugins.json"],
  ["generate-llms-txt.py", "llms.txt"],
];
for (const [script, output] of outputs) {
  // A framework build must not replace an existing documentation/data snapshot
  // with today's external catalog. Explicit generation and publishing own refreshes.
  if (existsSync(resolve(website, "docs", output))) continue;
  if (script === "extract-skills.py") await ensureSkillsIndex();
  run(python, [resolve(website, "scripts", script)]);
}
run(process.execPath, [resolve(website, "scripts/generate-catalog-pages.mjs")]);
run(process.execPath, [resolve(website, "scripts/build-components.mjs")]);
