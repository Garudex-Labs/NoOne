import { mkdir, readFile, writeFile, rm, readdir } from "node:fs/promises";
import { createRequire } from "node:module";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { catalogRenderer, literalCatalogMarkup } from "./render-catalog.mjs";

const require = createRequire(import.meta.url);
const { fetchReadme, renderReadme } = require("./plugin-readme.cjs");
const website = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const docs = join(website, "docs");
const entries = JSON.parse(await readFile(join(docs, "api/plugins.json"), "utf8"));
const meta = JSON.parse(await readFile(join(docs, "api/plugins-meta.json"), "utf8"));
const cacheArgument = process.argv.indexOf("--readme-cache");
const cache = cacheArgument < 0 ? join(website, ".cache/plugin-readmes") : resolve(process.argv[cacheArgument + 1]);
const offline = process.argv.includes("--offline");
const renderer = await catalogRenderer();
const authors = new Map();
for (const entry of entries) {
  const slug = entry.maintainerSlug || "unknown";
  const author = authors.get(slug) || { slug, name: entry.maintainer || slug, plugins: [] };
  author.plugins.push(entry);
  authors.set(slug, author);
}

async function page(path, title, description, component, data) {
  const file = join(docs, `${path}.mdx`);
  await mkdir(dirname(file), { recursive: true });
  const content = [
    "---", `title: ${JSON.stringify(title)}`, `description: ${JSON.stringify(description)}`,
    "mode: custom", ...(data.plugin ? ['"og:type": "website"', ...(data.plugin.image ? [`"og:image": ${JSON.stringify(data.plugin.image)}`] : [])] : []), "---", "",
    `{/* Generated by website/scripts/generate-catalog-pages.mjs. */}`, "",
    `export const catalogHtml = JSON.parse(${JSON.stringify(JSON.stringify(literalCatalogMarkup(renderer.render(component, data), renderer.copiedMarkup, path.startsWith('zh-Hans/') ? 'zh-Hans' : ''))).replaceAll("{", "\\u007b").replaceAll("}", "\\u007d")});`, "",
    '<div dangerouslySetInnerHTML={{__html: catalogHtml}} />', "",
  ].join("\n");
  let previous;
  try {
    previous = await readFile(file, "utf8");
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
  }
  if (previous !== content) await writeFile(file, content);
}

const readmes = {};
const wanted = entries.filter((entry) => entry.readme && entry.readmeUrl);
let next = 0;
let fetched = 0;
async function worker() {
  while (next < wanted.length) {
    const entry = wanted[next++];
    const result = await fetchReadme(entry.readmeUrl, cache, console.warn, { offline });
    if (result) {
      readmes[entry.name] = { html: await renderReadme(result.markdown, result.url), url: result.url };
      fetched++;
    }
  }
}
await Promise.all(Array.from({ length: Math.min(12, wanted.length) }, worker));
if (offline) {
  const previous = JSON.parse(await readFile(join(docs, "api/catalog-pages.json"), "utf8"));
  const knownMissing = new Set(previous.missingReadmes || []);
  const unavailable = wanted.filter((entry) => !readmes[entry.name] && !knownMissing.has(entry.readmeUrl));
  if (unavailable.length) throw new Error(`Offline catalog cache is incomplete for ${unavailable.length} pinned READMEs; existing pages were not replaced`);
}
const routes = [];
for (const entry of entries) {
  const author = authors.get(entry.maintainerSlug || "unknown");
  const data = {
    plugin: entry,
    readmeHtml: readmes[entry.name]?.html || null,
    readmeSourceUrl: readmes[entry.name]?.url || null,
    author: { slug: author.slug, name: author.name, count: author.plugins.length },
    moreByAuthor: author.plugins.filter((plugin) => plugin.name !== entry.name),
    generatedAt: meta.generatedAt || null,
    starsFetchedAt: meta.starsFetchedAt || null,
  };
  const text = entry.description || "";
  const disclosure = text.search(/\bDisclosure\s*[—–:-]\s*/);
  const prose = disclosure < 0 ? text : text.slice(0, disclosure).trim();
  const description = (prose || entry.description || `${entry.name} — an agent plugin`).slice(0, 160);
  for (const prefix of ["", "zh-Hans/"]) {
    const path = `${prefix}plugins/${entry.name}`;
    await page(path, `${entry.name} · Plugin Catalog`, description, "PluginPage", data);
    routes.push(path);
  }
}
for (const author of authors.values()) {
  const data = {
    author: { slug: author.slug, name: author.name, count: author.plugins.length },
    plugins: author.plugins,
    generatedAt: meta.generatedAt || null,
  };
  for (const prefix of ["", "zh-Hans/"]) {
    const path = `${prefix}plugins/by/${author.slug}`;
    await page(path, `Plugins by ${author.name} · Plugin Catalog`,
      `${author.plugins.length} agent plugin${author.plugins.length === 1 ? "" : "s"} by ${author.name} in the reviewed catalog.`,
      "AuthorPage", data);
    routes.push(path);
  }
}
const manifest = join(docs, "api/catalog-pages.json");
const active = new Set(routes);
async function prune(directory, prefix) {
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const path = join(directory, entry.name);
    const route = `${prefix}/${entry.name.replace(/\.mdx$/, "")}`;
    if (entry.isDirectory()) await prune(path, route);
    else if (entry.name.endsWith(".mdx") && !active.has(route) &&
      (await readFile(path, "utf8")).includes("{/* Generated by website/scripts/generate-catalog-pages.mjs. */}")) await rm(path);
  }
}
for (const prefix of ["plugins", "zh-Hans/plugins"]) await prune(join(docs, prefix), prefix);
await writeFile(manifest, JSON.stringify({
  plugins: entries.length, authors: authors.size, readmesRequested: wanted.length,
  readmesRendered: fetched, missingReadmes: wanted.filter((entry) => !readmes[entry.name]).map((entry) => entry.readmeUrl), routes,
}, null, 2) + "\n");
const configFile = join(docs, "docs.json");
const config = JSON.parse(await readFile(configFile, "utf8"));
for (const language of config.navigation.languages) {
  const prefix = language.language === "en" ? "" : "zh-Hans/";
  const hidden = language.groups.find((group) => group.hidden === true && group.group === "Docs");
  if (!hidden) throw new Error("Missing catalog navigation group");
  hidden.pages = [
    ...hidden.pages.filter((path) => typeof path !== "string" || !path.startsWith(`${prefix}plugins/`)),
  ];
}
const configText = JSON.stringify(config, null, 2) + "\n";
if (configText !== await readFile(configFile, "utf8")) await writeFile(configFile, configText);
console.log(`Prepared ${entries.length} plugin and ${authors.size} author pages in both languages; ${fetched}/${wanted.length} pinned READMEs`);
