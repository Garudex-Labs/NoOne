const COMPONENTS = new Map<Icon, Icon>()

/** Resolve the existing menu/tool/persisted vocabulary to one SVG family. */
export function getAppIcon(name: string): Icon {
  const Component = Object.hasOwn(ICONS, name) ? ICONS[name] : IconHelpCircle
  const existing = COMPONENTS.get(Component)

  if (existing) {return existing}

  const Glyph: Icon = ({ className, ...props }) => (
    <Component
      aria-hidden={props.title || props.role || props['aria-label'] || props['aria-labelledby'] ? undefined : true}
      className={['noone-icon', className].filter(Boolean).join(' ')}
      size="1em"
      {...props}
    />
  )

  COMPONENTS.set(Component, Glyph)

  return Glyph
}

export interface AppIconProps extends IconProps {
  name: string
  spinning?: boolean
}

/** Dynamic presentation boundary; static actions should use named exports from ./icons. */
export function AppIcon({ name, className, size = 16, spinning, style, ...props }: AppIconProps) {
  const Component = getAppIcon(name)

  return (
    <Component
      aria-hidden={props.title || props.role || props['aria-label'] || props['aria-labelledby'] ? undefined : true}
      className={['noone-icon', spinning && 'noone-icon-spin', className].filter(Boolean).join(' ')}
      size="1em"
      style={{ ...(size != null && size !== '' ? { fontSize: size } : {}), ...style }}
      {...props}
    />
  )
}
