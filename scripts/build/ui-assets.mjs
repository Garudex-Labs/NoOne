// Regenerate shared font CSS from the typography contract. No network or runtime build is needed.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { isMain } from './frontend-common.mjs'

const root = new URL('../../agent_cli/data/ui/', import.meta.url)
export function typographyCss(data) {
  const notices = ['Inter-OFL.txt', 'JetBrainsMono-OFL.txt', 'Tabler-MIT.txt']
    .map(name => readFileSync(new URL(name, root), 'utf8')).join('\n\n')
  const faces = [
    ['Inter', 'normal', '100 900', 'InterVariable.woff2'],
    ['Inter', 'italic', '100 900', 'InterVariable-Italic.woff2'],
    ['JetBrains Mono', 'normal', '400', 'JetBrainsMono-Regular.woff2'],
    ['JetBrains Mono', 'normal', '700', 'JetBrainsMono-Bold.woff2'],
    ['JetBrains Mono', 'italic', '400', 'JetBrainsMono-Italic.woff2'],
  ].map(([family, style, weight, file]) => `@font-face {
  font-family: '${family}';
  font-style: ${style};
  font-weight: ${weight};
  font-display: swap;
  src: url('./fonts/${file}') format('woff2');
}`).join('\n')
  const roles = Object.entries(data.scale).map(([role, size]) => `  --noone-text-${role}: ${size};`).join('\n')
  const weights = Object.entries(data.weight).map(([role, weight]) => `  --noone-weight-${role}: ${weight};`).join('\n')
  return `/*! Third-party font/icon notices\n${notices}\n*/\n/* Generated by scripts/build/ui-assets.mjs from typography.json. */
${faces}
:root {
  --noone-font-sans: ${data.sans};
  --noone-font-mono: ${data.mono};
${roles}
${weights}
  --noone-leading-body: 1.55;
  --noone-leading-heading: 1.25;
  --noone-leading-label: 1.4;
}
.noone-icon { display: inline-block; flex-shrink: 0; vertical-align: -0.125em; }
.noone-icon-spin { animation: noone-icon-spin 1.5s linear infinite; }
@keyframes noone-icon-spin { to { transform: rotate(360deg); } }
@media (prefers-reduced-motion: reduce) { .noone-icon-spin { animation: none; } }
`
}
if (isMain(import.meta.url)) {
  const data = JSON.parse(readFileSync(new URL('typography.json', root), 'utf8'))
  const css = typographyCss(data)
  writeFileSync(fileURLToPath(new URL('typography.css', root)), css)
  const handoff = new URL('../desktop-update/ui.html', import.meta.url)
  const font = readFileSync(new URL('fonts/InterVariable.woff2', root)).toString('base64')
  const face = css.match(/@font-face \{[^}]+InterVariable\.woff2[^}]+\}/)[0]
    .replace("url('./fonts/InterVariable.woff2')", `url('data:font/woff2;base64,${font}')`)
  const block = `<!-- noone-typography:start -->\n<style>\n${face}\n</style>\n<!-- noone-typography:end -->`
  const html = readFileSync(handoff, 'utf8').replace(/<!-- noone-typography:start -->[\s\S]*?<!-- noone-typography:end -->/, block)
  writeFileSync(handoff, html)
}
